#!/usr/bin/env python3
"""
Score full-corpus predictions leave-one-prompt-out (offline, no API calls).

Each (prompt, review) prediction is scored against every applicable reference
label row EXCEPT rows generated by the prompt under evaluation. One prediction
per review may be compared against multiple reference rows (2 for generator
prompts v2/v3/v6, 3 for the others).

Writes the committed summary (data/evaluation/rescored_crossval_summary.json),
superseding the earlier 17-review re-scoring.

Usage:
    .venv/bin/python scripts/score_full_crossval.py
"""

import json
import sys
from datetime import datetime, timezone
from pathlib import Path

REPO_ROOT = Path(__file__).parent.parent
sys.path.insert(0, str(REPO_ROOT))
sys.path.insert(0, str(REPO_ROOT / 'src'))

from evaluation.evaluate_prompts import PromptEvaluator, _norm_prompt  # noqa: E402

PREDICTIONS = REPO_ROOT / 'data_local/evaluation/full_predictions.jsonl'
LABELS = REPO_ROOT / 'data_local/labeled/silver_standard_crossval.jsonl'
OUTPUT = REPO_ROOT / 'data/evaluation/rescored_crossval_summary.json'


def main():
    preds = {}  # (prompt_key, review_id) -> parsed prediction
    n_errors = 0
    for line in PREDICTIONS.read_text().splitlines():
        if line.strip():
            row = json.loads(line)
            key = (_norm_prompt(row['prompt_version']), row['review_id'])
            preds[key] = row['prediction']
            n_errors += row.get('error') is not None

    label_rows = [json.loads(line) for line in LABELS.read_text().splitlines()
                  if line.strip()]
    label_models = sorted({str(r.get('model')) for r in label_rows})
    generators = sorted({_norm_prompt(r.get('prompt_version', ''))
                         for r in label_rows if r.get('prompt_version')})

    results = []
    for prompt_key in ['v1', 'v2', 'v3', 'v4', 'v5', 'v6']:
        kept, prediction_map = [], {}
        for row in label_rows:
            if _norm_prompt(row.get('prompt_version', '')) == prompt_key:
                continue  # leave-one-prompt-out exclusion
            pred = preds.get((prompt_key, row['review_id']))
            if pred is None:
                continue
            kept.append(row)
            prediction_map[row['review_id']] = pred

        ordered_preds = [prediction_map[r['review_id']] for r in kept]
        unique_reviews = len({r['review_id'] for r in kept})
        metrics = PromptEvaluator.calculate_metrics(kept, ordered_preds)
        metrics['n_unparsed'] = sum(1 for p in ordered_preds if p is None)
        results.append({
            'prompt_version': f'{prompt_key}.0',
            'rows_before_exclusion': len(label_rows) // 3 * 3,
            'rows_excluded_as_self_labeled': sum(
                1 for r in label_rows
                if _norm_prompt(r.get('prompt_version', '')) == prompt_key),
            'n_label_rows': len(kept),
            'n_unique_reviews': unique_reviews,
            'k_shot': 0,
            'model': 'gpt-4o-mini',
            'rescored_agreement': {
                'theme_f1': metrics.get('theme_f1'),
                'theme_precision': metrics.get('theme_precision'),
                'theme_recall': metrics.get('theme_recall'),
                'sentiment_exact_agreement': metrics.get('sentiment_exact_agreement'),
                'sentiment_mae': metrics.get('sentiment_mae'),
                'risk_agreement': metrics.get('risk_agreement'),
            },
        })
        m = metrics
        print(f"{prompt_key}: {len(kept)} rows / {unique_reviews} reviews | "
              f"F1 {m.get('theme_f1', 0):.1%} | sentiment "
              f"{m.get('sentiment_exact_agreement', 0):.1%} | risk "
              f"{m.get('risk_agreement', 0):.1%}")

    payload = {
        'what_this_is': (
            'Leave-one-prompt-out agreement over the FULL 175-review corpus '
            '(predictions generated 2026-10-16, gpt-4o-mini, zero-shot). '
            'Reference labels are LLM-generated (silver); metrics are '
            'agreement with that labeler, NOT accuracy against human ground '
            'truth. Supersedes the earlier 17-review re-scoring of the '
            'February 2026 predictions, which covered only the first 50 '
            'label rows (all Reddit posts).'),
        'protocol': {
            'prediction_model': 'gpt-4o-mini',
            'temperature': 0.3,
            'k_shot': 0,
            'one_prediction_per_review_per_prompt': True,
            'lopo_exclusion': True,
            'predictions_failed': n_errors,
        },
        'label_provenance': {
            'label_type': 'llm_silver',
            'label_models': label_models,
            'generator_prompts': generators,
        },
        'rescored_at_utc': datetime.now(timezone.utc).isoformat(),
        'results': results,
    }

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(json.dumps(payload, indent=2))
    print(f'\nSaved to {OUTPUT}')


if __name__ == '__main__':
    main()
